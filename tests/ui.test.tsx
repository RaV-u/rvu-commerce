const dom = new JSDOM("<!doctype html><html><body></body></html>", {
  url: "http://localhost:8080",
});
Object.defineProperty(globalThis, "navigator", {
  value: dom.window.navigator,
  configurable: true,
});
Object.assign(globalThis, {
  window: dom.window,
  document: dom.window.document,
  HTMLElement: dom.window.HTMLElement,
  HTMLDialogElement: dom.window.HTMLDialogElement,
  FormData: dom.window.FormData,
  getComputedStyle: dom.window.getComputedStyle,
  IS_REACT_ACT_ENVIRONMENT: true,
});
dom.window.HTMLDialogElement.prototype.showModal = function () {
  this.setAttribute("open", "");
};
dom.window.HTMLDialogElement.prototype.close = function () {
  this.removeAttribute("open");
};
dom.window.HTMLElement.prototype.scrollIntoView = function () {};
const { render, screen, within, waitFor, cleanup } =
  await import("@testing-library/react");
const { default: userEvent } = await import("@testing-library/user-event");
let db: PGlite,
  server: PGLiteSocketServer,
  store: Awaited<ReturnType<typeof buildApp>>;
const originalFetch = globalThis.fetch;
before(async () => {
  db = await PGlite.create();
  server = new PGLiteSocketServer({ db, port: 0, maxConnections: 5 });
  await server.start();
  const url =
    "postgresql://postgres:postgres@" + server.getServerConn() + "/postgres";
  await migrate(url, "Local-Instructor-UI-2026!");
  store = await buildApp({
    databaseUrl: url,
    origin: "http://localhost:8080",
    cookieSecure: false,
    mode: "store",
  });
  store.pool.options.max = 1;
  let cookie = "";
  // In-process HTTP adapter, not a mocked business backend. Every response is generated by Fastify + SQL.
  globalThis.fetch = async (input, init) => {
    const headers = new Headers(init?.headers);
    headers.set("origin", "http://localhost:8080");
    headers.set("cookie", cookie);
    const response = await store.app.inject({
      method: (init?.method ?? "GET") as "GET",
      url: String(input),
      headers: Object.fromEntries(headers),
      ...(init?.body ? { payload: String(init.body) } : {}),
    });
    const value = response.headers["set-cookie"];
    if (value) cookie = (Array.isArray(value) ? value[0] : value).split(";")[0];
    return new Response(response.body, {
      status: response.statusCode,
      headers: { "content-type": "application/json" },
    });
  };
});
after(async () => {
  cleanup();
  globalThis.fetch = originalFetch;
  await store?.app.close();
  await server?.stop();
  await db?.close();
  dom.window.close();
});
